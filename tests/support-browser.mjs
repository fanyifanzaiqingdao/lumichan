async function noOverflow(page, selector) {
  const result=await page.locator(selector).evaluate(el=>({w:el.clientWidth,s:el.scrollWidth,doc:document.documentElement.scrollWidth,viewport:innerWidth}))
  assert.ok(result.s<=result.w+1,`${selector} overflows ${JSON.stringify(result)}`)
  assert.ok(result.doc<=result.viewport+1,'page has horizontal overflow')
}
