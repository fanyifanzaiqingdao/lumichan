let checks = 0
async function api(path, body, { cookie, token, csrf, status = 200 } = {}) {
  const r = await fetch(new URL(path, base), { method: body ? 'POST':'GET', headers: { ...(body ? { 'Content-Type':'application/json' }:{}), ...(cookie ? {Cookie:cookie}:{}), ...(token ? {Authorization:`Bearer ${token}`}:{}), ...(csrf ? {'X-CSRF-Token':csrf}:{}) }, body: body ? JSON.stringify(body):undefined })
  const raw = await r.text()
  assert.equal(r.status, status, `${path}: ${raw}`)
  checks++
  return { ...JSON.parse(raw), cookie:r.headers.getSetCookie().map(c=>c.split(';')[0]).join('; ') || cookie }
}
